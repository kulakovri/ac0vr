/* ps2_stats.c -- opt-in usage statistics and crash summaries sent to the project's owner (ACZ_STATS, stats_optin 2026-11-04;
   RELEASE_RESEARCH R14; docs/PRIVACY.md is the player's description, ps2_quit.c draws the question and the SHOW page).

   Nothing is sent before the player's answer, nothing when the answer is no, nothing from a build without a key (CMake reads
   posthog.secret into ps2_stats_key.h), nothing with ACZ_STATS=0 (the test scripts set it). The question comes once, at the
   real title screen (zero_vr.c zb_title_up; not over the logos), drawn by ps2_quit.c. The answer is in the settings file:
   [privacy] stats = 0|1, stats_asked = <date>, install_id = <32 hex, random at consent>; absent keys mean "ask".

   One `session` event per session: the document is kept in stats/pending_<stamp>.json next to the exe, written every 10 minutes
   (ACZ_STATS_EVERY) and at the exit, so a crash loses little, and sent at the exit (the exit waits at most 2 s) or at the next
   start. One `crash` event per crash report (ps2_crash.c): the "what" line without addresses, the exception code, the address
   relative to the exe, the top of the stack; never the report's log lines, they can hold folder names. A pending document holds
   no key: the project token goes into the request only.

   Outbound only: one HTTPS POST through WinHTTP (the system's TLS) to one named host (PostHog's capture endpoint for the region,
   https://eu.i.posthog.com/i/v0/e/), a background thread, 5 s timeouts, a failed send stays pending for the next start.
   No registry GUIDs, MAC addresses, user names, process lists or file paths in any document. Hardware comes from the APIs the
   runtime already calls. `$process_person_profile: false` keeps the events anonymous; `$ip: "0.0.0.0"` and `$geoip_disable: true`
   keep the address out of the stored event and turn the location lookup off (PostHog takes $ip from the request only when the
   event has none; docs/privacy/data-storage), whatever the project's own setting says. ACZ_STATS_GEOIP=1 leaves both out.

   Every document can be seen: ACZ_DEBUG_STATS=1 logs it, ENHANCEMENTS > SYSTEM > SHOW WHAT IS SENT shows it, ACZ_STATS_DRY=1
   logs and does not send. The document never holds or logs the project token. */
