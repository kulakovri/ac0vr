void ps2_stats_note_gpu(double ms, int flying, int gov_level) {
    double now;
    int b;
    if (!ps2_stats_collecting || !flying) return;
    b = (int)(ms * 10.0);
    if (b < 0) b = 0;
    if (b >= HIST_N) b = HIST_N - 1;
    st.gpu_hist[b]++;
    st.gpu_n++;
    now = ps2_wall_seconds();
    if (gov_level > 0 && st.last_gpu_t > 0.0 && now - st.last_gpu_t < 0.25) st.shed_s += now - st.last_gpu_t;
    st.last_gpu_t = now;
}
void ps2_stats_note_ee(double ms) {
    int b;
    if (!st.flying) return;
    b = (int)(ms * 10.0);
    if (b < 0) b = 0;
    if (b >= HIST_N) b = HIST_N - 1;
    st.ee_hist[b]++;
    st.ee_n++;
}
void ps2_stats_mission_begin(int mission, int aircraft) {
    if (!ps2_stats_collecting) return;
    pthread_mutex_lock(&st.mx);
    if (st.nm < MISSIONS_MAX) {
        st.m[st.nm].mission = mission;
        st.m[st.nm].aircraft = aircraft;
        snprintf(st.m[st.nm].result, sizeof st.m[st.nm].result, "left");
        st.nm++;
    } else st.m_dropped++;
    pthread_mutex_unlock(&st.mx);
}
void ps2_stats_mission_end(const char *result) {
    if (!ps2_stats_collecting) return;
    pthread_mutex_lock(&st.mx);
    if (st.nm > 0 && result && strcmp(st.m[st.nm - 1].result, "completed"))
        snprintf(st.m[st.nm - 1].result, sizeof st.m[st.nm - 1].result, "%s", result);
    pthread_mutex_unlock(&st.mx);
}

