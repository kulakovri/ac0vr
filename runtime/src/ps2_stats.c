void ps2_stats_tick(void) {
    static u64 next;
    if (!st.inited || !st.key[0]) return;
    u64 f = ps2_kernel_vblank_count();
    if (f < next) return;
    next = f + 30u;
    /* twice a second on the renderer thread: what only it may read */
    {
        const char *c = ps2_hotas_count() > 0 ? "HOTAS" : ps2_video_pad_class_name();
        pthread_mutex_lock(&st.mx);
        snprintf(st.controller, sizeof st.controller, "%s", c ? c : "none");
        if (ps2_xr_session_running()) st.xr_seen = 1;
        pthread_mutex_unlock(&st.mx);
        st.flying = ps2_quit_game_state() == PS2_QUIT_GAME_FLYING;
        if (st.refresh_hz <= 0.0) {                           /* (without XR_FB_display_refresh_rate: the frame period) */
            extern long long ps2_xr_display_period(void);
            long long per = ps2_xr_display_period();
            if (per > 1000000) st.refresh_hz = 1e9 / (double)per;
        }
    }
    /* the earlier sessions' documents: only once the game's screen is up, never at start before a UI */
    if (ps2_stats_collecting && !st.send_old_done && f >= 600u) {
        st.send_old_done = 1;
        pthread_mutex_lock(&st.mx);
        st.th_send_old = 1;
        pthread_cond_broadcast(&st.cv);
        pthread_mutex_unlock(&st.mx);
    }
}
void ps2_stats_exit(void) {
    if (!st.inited || !ps2_stats_collecting || !st.th_on) return;
    double t0 = ps2_wall_seconds();
    struct timespec ts;
    int done;
    clock_gettime(CLOCK_REALTIME, &ts);
    ts.tv_sec += 2;
    pthread_mutex_lock(&st.mx);
    st.th_exit = 1;
    pthread_cond_broadcast(&st.cv);
    while (!st.th_done)
        if (pthread_cond_timedwait(&st.cv, &st.mx, &ts) != 0) break;
    done = st.th_done;
    pthread_mutex_unlock(&st.mx);
    ps2_log("stats: the exit waited %.3f s (at most 2): %s", ps2_wall_seconds() - t0,
            done ? "the session's document is done" : "still sending; a file left behind goes at the next start");
}

